"""Lists how often the database synced its write-ahead log in every run of
round 2's passes, from the recorded results, and prints Markdown.

Each run records PostgreSQL's WAL counters over its bench command
(db_activity.wal in results.json). A run's sync rate is wal_sync, the number
of times PostgreSQL synced the write-ahead log to disk, over the bench window
(window_s). Beside it are the run's commands per second, its database CPU per
command, and its event insert's execution time per row from
pg_stat_statements, the figures the README gives elsewhere. Runs are listed
by their start, in the laptop's local time, as each run's run.md records it.

    py -3 sync_rates.py [results folder] > round2-sync-rates.md

The results folder defaults to the one beside this folder.
"""

import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
RESULTS = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE.parent / "results"
PASSES = [
    ("round2-laptop", "Round 2's laptop pass"),
    ("round2-shape", "Round 2's code-shape pass"),
    ("round2-diag", "Round 2's diagnostic pass, with its follow-up repeats"),
    ("round2-fix", "Round 2's fix pass"),
    ("round2-followup", "Round 2's follow-up tests"),
    ("round2-flush", "Round 2's flush-timing night"),
]


def load(folder, name):
    run = json.loads((folder / "results.json").read_text(encoding="utf-8"))["runs"][0]
    started = re.search(r"Started (\d{4}-\d\d-\d\d)T(\d\d:\d\d)", (folder / "run.md").read_text(encoding="utf-8"))
    bench, wal = run["bench"], run["db_activity"]["wal"]
    insert_ms = insert_rows = 0
    for statement in run.get("top_statements") or []:
        if " ".join(statement["query"].split()).upper().startswith("INSERT INTO CORE.EVENT"):
            insert_ms += statement["total_ms"]
            insert_rows += statement["rows"]
    return {
        "started": f"{started.group(1)} {started.group(2)}",
        "run": folder.name[11:].replace(f"{name}-", "", 1),
        "rate": bench["succeeded"] / bench["elapsed_s"],
        "syncs": wal["wal_sync"] / run["window_s"],
        "db": (run.get("cpu_ms_per_command") or {}).get("db"),
        "insert": insert_ms / insert_rows if insert_rows else None,
    }


def f(value, digits):
    return "" if value is None else f"{value:,.{digits}f}"


def main():
    out = ["# Round 2's WAL sync rates", "",
           "Generated by [sync_rates.py](sync_rates.py) from the recorded results. For every run of round 2's passes, "
           "in the order the runs started: the start in the laptop's local time, commands per second, how many times "
           "per second the database synced its write-ahead log to disk over the bench command, database CPU in "
           "milliseconds per command, and the event insert's execution time in milliseconds per row written, from "
           "`pg_stat_statements`, which includes its trigger and foreign-key check. A run's name gives its side, "
           "workload, worker count, and block."]
    for name, title in PASSES:
        rows = sorted((load(folder, name) for folder in RESULTS.glob(f"????-??-??-{name}-*")
                       if (folder / "results.json").exists()), key=lambda r: r["started"])
        out += ["", f"## {title}", "",
                f"*{len(rows)} runs, in the order they started.*", "",
                "| Started | Run | Commands per second | WAL syncs per second | Database CPU, ms per command "
                "| Event insert, ms per row |",
                "| --- | --- | --- | --- | --- | --- |"]
        for r in rows:
            out.append(f"| {r['started']} | {r['run']} | {f(r['rate'], 1)} | {f(r['syncs'], 1)} | {f(r['db'], 2)} "
                       f"| {f(r['insert'], 3)} |")
    sys.stdout.reconfigure(newline="\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
